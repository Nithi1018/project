CREATE TABLE CUSTOMER_SRC (
  CUST_ID NUMBER(6) PRIMARY KEY, FIRST_NAME VARCHAR2(30) NOT NULL, LAST_NAME VARCHAR2(30),
  EMAIL VARCHAR2(60), CITY VARCHAR2(30), STATE VARCHAR2(5), REGION_CODE CHAR(1), JOIN_DATE DATE);

CREATE TABLE PRODUCT_MST (
  PROD_ID VARCHAR2(5) PRIMARY KEY, PROD_NAME VARCHAR2(40) NOT NULL,
  CATEGORY VARCHAR2(20), UNIT_PRICE NUMBER(10,2));

CREATE TABLE STORE_MST (
  STORE_ID VARCHAR2(5) PRIMARY KEY, STORE_NAME VARCHAR2(40), CITY VARCHAR2(30), REGION_CODE CHAR(1));

CREATE TABLE REGION_MST (REGION_CODE CHAR(1) PRIMARY KEY, REGION_NAME VARCHAR2(20));

CREATE TABLE ORDERS_ONLINE (
  ORDER_ID NUMBER(8) PRIMARY KEY, CUST_ID NUMBER(6), PROD_ID VARCHAR2(5), QTY NUMBER(4),
  DISCOUNT_PCT NUMBER(5,2), ORDER_DATE DATE, ORDER_STATUS VARCHAR2(12));

-- TARGET TABLES
CREATE TABLE TGT_ORDERS_HIGH (
  ORDER_ID NUMBER(8), CHANNEL VARCHAR2(10), STORE_ID VARCHAR2(5), ORDER_DATE DATE,
  CUST_ID NUMBER(6), CUSTOMER_NAME VARCHAR2(70), PROD_NAME VARCHAR2(40), CATEGORY VARCHAR2(20),
  QTY NUMBER(4), GROSS_AMT NUMBER(12,2), DISCOUNT_AMT NUMBER(12,2), NET_AMT NUMBER(12,2),
  ORDER_BAND VARCHAR2(8));
CREATE TABLE TGT_ORDERS_MEDIUM AS SELECT * FROM TGT_ORDERS_HIGH WHERE 1=0;
CREATE TABLE TGT_ORDERS_LOW    AS SELECT * FROM TGT_ORDERS_HIGH WHERE 1=0;

CREATE TABLE TGT_CUSTOMER_SPEND (
  CUST_ID NUMBER(6), CUSTOMER_NAME VARCHAR2(70), ORDER_COUNT NUMBER(5),
  TOTAL_NET_AMT NUMBER(14,2), CUST_TIER VARCHAR2(8));

CREATE TABLE TGT_REGION_CATEGORY_SALES (
  REGION_CODE CHAR(1), REGION_NAME VARCHAR2(20), CATEGORY VARCHAR2(20),
  TOTAL_QTY NUMBER(8), ORDER_COUNT NUMBER(6), TOTAL_NET_AMT NUMBER(14,2));

CREATE TABLE TGT_TOP_PRODUCTS (
  CATEGORY VARCHAR2(20), RANK_NO NUMBER(3), PROD_ID VARCHAR2(5),
  PROD_NAME VARCHAR2(40), TOTAL_NET_AMT NUMBER(14,2));

CREATE TABLE DIM_CUSTOMER (
  CUST_KEY NUMBER(8) PRIMARY KEY, CUST_ID NUMBER(6) NOT NULL, FIRST_NAME VARCHAR2(30),
  LAST_NAME VARCHAR2(30), EMAIL VARCHAR2(60), CITY VARCHAR2(30), STATE VARCHAR2(5),
  REGION_CODE CHAR(1), CREATED_DT DATE, UPDATED_DT DATE);

-- Bonus (Normalizer)
CREATE TABLE TGT_STORE_TARGET_QTR (
  STORE_ID VARCHAR2(5), QTR_NO NUMBER(1), QTR_NAME VARCHAR2(2), TARGET_AMT NUMBER(12,2));




